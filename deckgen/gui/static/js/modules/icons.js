export function iconSvg(name, size = 14) {
  const path = ICON_PATHS[name] || '';
  if (!path) return '';
  return `<svg class="dg-ico" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${path}</svg>`;
}

export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-ico]').forEach((el) => {
    const name = el.getAttribute('data-ico');
    const size = parseInt(el.getAttribute('data-ico-size') || '14', 10) || 14;
    const svg = iconSvg(name, size);
    if (svg) el.outerHTML = svg;
  });
}

if (typeof window !== 'undefined') {
  window.__dgIcon = iconSvg;
  window.__dgHydrateIcons = hydrateIcons;
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => hydrateIcons(document));
  } else {
    hydrateIcons(document);
  }
}
